#!/usr/bin/env node
/**
 * gen-word-lists — regenerate src/lib/digest/wordLists.ts.
 *
 * The lists must be SOURCE, not data files: SvelteKit's build ships JS and
 * leaves .txt behind, so an fs read works in dev and throws in the container.
 *
 *   node ui/scripts/gen-word-lists.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UI = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIGEST = path.join(UI, 'src/lib/digest');
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const common = fs.readFileSync(path.join(DIGEST, 'common-words.txt'), 'utf8').trim();
const long = fs.readFileSync(path.join(DIGEST, 'long-words.txt'), 'utf8').trim();

fs.writeFileSync(
	path.join(DIGEST, 'wordLists.ts'),
	`/**
 * wordLists — the frequency list and dictionary, as modules rather than files.
 *
 * GENERATED by ui/scripts/gen-word-lists.mjs. Do not edit by hand.
 *
 * These were .txt files read with fs at runtime, which worked in dev and broke
 * in the container: SvelteKit bundles JS and does not copy .txt assets, so the
 * read threw ENOENT and the whole chat section silently vanished.
 */

/** The 10,000 most common English words, most frequent first. */
export const COMMON_WORDS_RAW = \`${esc(common)}\`;

/** Lowercase dictionary words of 7+ letters — no proper nouns. */
export const LONG_WORDS_RAW = \`${esc(long)}\`;
`,
);
console.error(
	`[ok] wordLists.ts — ${common.split('\n').length} common, ${long.split('\n').length} dictionary`,
);
